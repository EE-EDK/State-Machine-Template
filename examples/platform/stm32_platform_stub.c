/**
 * @brief Check if timeout has elapsed with 32-bit wraparound safety
 *
 * Uses unsigned subtraction which handles the 32-bit counter wraparound
 * correctly (works as long as the timeout is less than ~49.7 days).
 */
bool SM_Platform_IsTimeout(uint32_t start, uint32_t timeout_ms)
{
    uint32_t now = SM_Platform_GetTimeMs();

    /* Unsigned subtraction handles wraparound:
     * e.g., now=5, start=0xFFFFFFFE -> (5 - 0xFFFFFFFE) = 7 */
    return (now - start) >= timeout_ms;
}

