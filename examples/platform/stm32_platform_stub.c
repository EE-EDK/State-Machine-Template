/* ============================================================================
 * RESET REASON
 *
 * The RCC_CSR register contains flags indicating the cause of the last reset.
 * Multiple flags can be set simultaneously (e.g., POR + BOR on initial
 * power-up). This implementation checks in priority order and clears the
 * flags after reading.
 *
 * Flag names may differ slightly between STM32 families. Common ones:
 *   RCC_FLAG_IWDGRST  -- Independent watchdog reset
 *   RCC_FLAG_SFTRST   -- Software reset (NVIC_SystemReset)
 *   RCC_FLAG_PINRST   -- NRST pin reset
 *   RCC_FLAG_BORRST   -- Brown-out reset
 *   RCC_FLAG_PORRST   -- Power-on reset (some families use RCC_FLAG_PWRRST)
 * ========================================================================= */

/**
 * @brief Determine the cause of the last system reset
 *
 * Reads RCC reset flags, maps to SM_ResetReason_t, and clears the flags
 * so the next reset produces a clean reading.
 *
 * @return Reset reason code
 */
SM_ResetReason_t SM_Platform_GetResetReason(void)
{
    SM_ResetReason_t reason = SM_RESET_UNKNOWN;

    /*
     * -- Check flags in priority order (most specific first)
     *
     * if (__HAL_RCC_GET_FLAG(RCC_FLAG_IWDGRST)) {
     *     reason = SM_RESET_WATCHDOG;
     * } else if (__HAL_RCC_GET_FLAG(RCC_FLAG_SFTRST)) {
     *     reason = SM_RESET_SOFTWARE;
     * } else if (__HAL_RCC_GET_FLAG(RCC_FLAG_BORRST)) {
     *     reason = SM_RESET_BROWNOUT;
     * } else if (__HAL_RCC_GET_FLAG(RCC_FLAG_PINRST)) {
     *     reason = SM_RESET_EXTERNAL;
     * } else if (__HAL_RCC_GET_FLAG(RCC_FLAG_PORRST)) {
     *     reason = SM_RESET_POR;
     * }
     *
     * -- Clear all reset flags so next reset is clean
     * __HAL_RCC_CLEAR_RESET_FLAGS();
     */

    return reason;
}

